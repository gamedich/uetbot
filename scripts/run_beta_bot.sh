#!/bin/bash
# Запуск тестового бота (ветка beta) из папки /root/uetbot2
set -e

cd /root/uetbot2

if grep -q "ВСТАВЬТЕ_ТОКЕН_ТЕСТОВОГО_БОТА_СЮДА" .env; then
    echo "======================================================================"
    echo "⚠️ ВНИМАНИЕ: Перед запуском тестового бота впишите его токен в файл:"
    echo "   /root/uetbot2/.env (параметр TG_BOT_TOKEN=...)"
    echo "======================================================================"
    exit 1
fi

echo "🚀 Запуск тестового бота (ветка beta, порт 8082)..."
exec /root/uetbot/venv/bin/python bot.py
